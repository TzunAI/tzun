/**
 * Python packaging: what reaches PyPI is built fresh from source, and both
 * the wheel and the sdist carry the model catalog.
 *
 * Two independent ways to publish a broken release that, because PyPI
 * versions are immutable, could never be corrected:
 *
 *  (a) A built wheel or sdist tracked in git. It is a second publish path
 *      that drifts silently from source while claiming the same version,
 *      so it can ship missing modules or stale code. No artifact under
 *      python/dist or python-stub/dist may be tracked, and .gitignore must
 *      not re-enable python/dist.
 *  (b) A catalog force-included from ../data into the wheel only. ../data
 *      is outside the sdist root, so a wheel built from the sdist would have
 *      no catalog, and the loader would turn that into a silent empty
 *      catalog. The catalog ships as ordinary package data, byte-identical
 *      to the seed, regenerated by codegen and drift-checked in CI.
 */
import { readFileSync, existsSync } from 'fs';
import { execFileSync } from 'child_process';
import { join } from 'path';

const ROOT = join(__dirname, '..', '..');

function read(rel: string): string {
  return readFileSync(join(ROOT, rel), 'utf-8');
}

describe('python packaging', () => {
  it('tracks no built Python distribution artifacts', () => {
    // A checked-in wheel is a second, unversioned publish path that drifts
    // silently from source. python-publish.yml (fresh build from the tag,
    // OIDC, PEP 740 attestations) is the only publish path.
    const tracked = execFileSync('git', ['ls-files', 'python/dist', 'python-stub/dist'], {
      cwd: ROOT,
      encoding: 'utf-8',
    })
      .split('\n')
      .filter(Boolean);
    expect(tracked).toEqual([]);
  });

  it('does not re-enable tracking of python/dist in .gitignore', () => {
    expect(read('.gitignore')).not.toMatch(/^\s*!python\/dist\//m);
  });

  it('ships the known-models catalog as ordinary package data, not a wheel-only force-include', () => {
    // Strip TOML comments: the file's comments name force-include and
    // ../data/ when explaining why neither is used.
    const pyproject = read('python/pyproject.toml')
      .split('\n')
      .filter((l) => !l.trimStart().startsWith('#'))
      .join('\n');
    // A force-include of ../data reaches outside the sdist root; nothing may
    // do that.
    expect(pyproject).not.toMatch(/force-include/);
    expect(pyproject).not.toMatch(/\.\.\/data\//);
    expect(existsSync(join(ROOT, 'python/src/tzun_sdk/_data/known-models.json'))).toBe(true);
  });

  it('keeps the Python catalog byte-identical to the seed catalog', () => {
    // The two SDKs must agree on the catalog, digest included.
    const seed = readFileSync(join(ROOT, 'data/known-models.json'));
    const bundled = readFileSync(join(ROOT, 'python/src/tzun_sdk/_data/known-models.json'));
    expect(bundled.equals(seed)).toBe(true);
    // Guard against both files being empty, which would pass vacuously.
    expect(JSON.parse(seed.toString('utf-8')).entries.length).toBeGreaterThan(0);
  });

  it("installs the 'anchor' extra in every job that runs the anchor tests, which fail under CI without it", () => {
    // python/tests/attestation/_anchor_extra.py and the cross-SDK anchor tests fail
    // at collection under CI when the extra is missing, which stops the whole run.
    const ci = read('.github/workflows/ci.yml');
    expect(ci).toMatch(/cd python\n\s+pip install --upgrade pip\n\s+pip install -e '\.\[anchor\]'\n/);
    expect(ci).toMatch(/pip install -e '\.\[anchor\]' pytest pytest-asyncio\n\s+- name: Run cross-SDK suite/);
    expect(ci).not.toMatch(/pip install -e \.(\s|$)/m);
    expect(read('.github/workflows/anvil.yml')).toMatch(/pip install -e '\.\[anchor\]' pytest pytest-asyncio/);
  });

  it('regenerates the Python catalog from codegen, and CI checks it for drift', () => {
    expect(read('scripts/codegen-python.ts')).toMatch(/KNOWN_MODELS_DST/);
    expect(read('.github/workflows/ci.yml')).toMatch(
      /git diff --exit-code[^\n]*python\/src\/tzun_sdk\/_data\//
    );
  });
});
