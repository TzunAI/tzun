import { NotificationChannel, TamperIncident, TamperSeverity, SlackNotificationConfig } from '@tzun/engine';

// ---------------------------------------------------------------------------
// Severity colour and emoji maps
// ---------------------------------------------------------------------------

const SEVERITY_COLORS: Record<TamperSeverity, string> = {
  critical: '#dc3545',
  warning: '#ffc107',
  info: '#17a2b8',
};

const SEVERITY_EMOJI: Record<TamperSeverity, string> = {
  critical: ':rotating_light:',
  warning: ':warning:',
  info: ':information_source:',
};

// ---------------------------------------------------------------------------
// SlackChannel
// ---------------------------------------------------------------------------

/**
 * Slack Channel (Tier 3 -- Enterprise)
 *
 * Posts to Slack via incoming webhook URL.
 * Formats incidents as rich Block Kit messages with severity colour-coding.
 */
export class SlackChannel implements NotificationChannel {
  readonly name = 'slack';
  private fetchFn: typeof fetch;

  constructor(
    private config: SlackNotificationConfig,
    fetchFn?: typeof fetch,
  ) {
    this.fetchFn = fetchFn ?? globalThis.fetch;
  }

  async send(incident: TamperIncident): Promise<void> {
    const color = SEVERITY_COLORS[incident.severity];
    const emoji = SEVERITY_EMOJI[incident.severity];

    const affectedRecords = incident.affectedRecords.length > 0
      ? incident.affectedRecords.map((r) => `\`${r}\``).join(', ')
      : 'none';

    const blocks = [
      {
        type: 'header',
        text: {
          type: 'plain_text',
          text: `${emoji} Tzun Tamper Alert: ${incident.type.replace(/_/g, ' ')}`,
          emoji: true,
        },
      },
      {
        type: 'section',
        fields: [
          { type: 'mrkdwn', text: `*Severity:*\n${incident.severity.toUpperCase()}` },
          { type: 'mrkdwn', text: `*Incident ID:*\n\`${incident.id}\`` },
          { type: 'mrkdwn', text: `*Detected At:*\n${incident.detectedAt}` },
          { type: 'mrkdwn', text: `*Status:*\n${incident.status}` },
        ],
      },
      {
        type: 'section',
        text: {
          type: 'mrkdwn',
          text: `*Affected Records:* ${affectedRecords}`,
        },
      },
      {
        type: 'context',
        elements: [
          {
            type: 'mrkdwn',
            text: `Event type: \`${incident.type}\` | Generated by Tzun SDK`,
          },
        ],
      },
    ];

    const payload: Record<string, unknown> = {
      blocks,
      attachments: [{ color, blocks: [] }],
    };

    if (this.config.username) {
      payload.username = this.config.username;
    }
    if (this.config.iconEmoji) {
      payload.icon_emoji = this.config.iconEmoji;
    }

    // Abort after the timeout. Dispatch is fire-and-forget, so a stalled
    // endpoint blocks nothing, but without a timeout each pending promise
    // would stay open for as long as the process lives.
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), this.config.timeoutMs ?? 5000);
    let response: Response;
    try {
      response = await this.fetchFn(this.config.webhookUrl, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload),
        redirect: 'error',
        signal: controller.signal,
      });
    } finally {
      clearTimeout(timeoutId);
    }

    if (!response.ok) {
      throw new Error(`Slack webhook returned HTTP ${response.status}`);
    }
  }

  async test(): Promise<void> {
    const payload = {
      text: 'Tzun SDK: notification channel test. If you see this, Slack integration is working.',
    };

    // Abort after the timeout. Dispatch is fire-and-forget, so a stalled
    // endpoint blocks nothing, but without a timeout each pending promise
    // would stay open for as long as the process lives.
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), this.config.timeoutMs ?? 5000);
    let response: Response;
    try {
      response = await this.fetchFn(this.config.webhookUrl, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload),
        redirect: 'error',
        signal: controller.signal,
      });
    } finally {
      clearTimeout(timeoutId);
    }

    if (!response.ok) {
      throw new Error(`Slack webhook test returned HTTP ${response.status}`);
    }
  }
}
