/**
 * The codegen-drift guard has no clause that can never fail.
 *
 * ci.yml runs `git diff --exit-code <paths>` after `pnpm run codegen:python`.
 * codegen-python.ts writes `_generated/models.py` and files under `_data/`
 * (`known-models.json`, `tsa-authorities.json`), and no script in the repo
 * writes anything under `schema/`. A path on the guard that nothing writes is
 * decoration: it cannot fail, while reading as coverage, and a reader who
 * trusts the path list believes a contract is protected when it is not.
 *
 * `_generated/canonical.py` and `_generated/chain.py` sit beside the generated
 * files but are never regenerated, so their banners must say they are
 * hand-maintained, not "AUTOGENERATED ... DO NOT EDIT", and must not name
 * `src/engine/canonical.ts`, a path that does not exist.
 *
 * These tests assert the guard's paths are exactly what the generator writes —
 * so a clause that cannot fire is caught, and so is a new generated file left
 * out of the guard.
 */
import { readFileSync, existsSync } from 'fs';
import { execFileSync, spawnSync } from 'child_process';
import { join } from 'path';

const ROOT = join(__dirname, '..', '..');
const read = (rel: string) => readFileSync(join(ROOT, rel), 'utf-8');

/** Paths named on the drift guard's `git diff --exit-code` line in ci.yml. */
function guardPaths(): string[] {
  const ci = read('.github/workflows/ci.yml');
  const m = ci.match(/git diff --exit-code ([^;\n]*?)\s*;/);
  expect(m).not.toBeNull();
  return m![1].trim().split(/\s+/).filter(Boolean);
}

/** Repo-relative paths `scripts/codegen-python.ts` writes. */
function generatedPaths(): string[] {
  const src = read('scripts/codegen-python.ts');
  const writes = [...src.matchAll(/writeFileSync\(\s*([A-Za-z_$][\w$]*)/g)].map((m) => m[1]);
  expect(writes.length).toBeGreaterThan(0);

  // Resolve each `const NAME = join(...)` to a repo-relative path.
  const resolved: string[] = [];
  for (const name of new Set(writes)) {
    const decl = src.match(
      new RegExp(`const ${name} = join\\(([^;]*?)\\);`, 's'),
    );
    expect(decl).not.toBeNull();
    const parts = [...decl![1].matchAll(/'([^']+)'/g)].map((m) => m[1]);
    // The leading identifier is a directory const; walk it back to its own
    // join() until we bottom out at REPO_ROOT.
    let head = decl![1].trim().split(',')[0].trim();
    while (head !== 'REPO_ROOT') {
      const parent = src.match(new RegExp(`const ${head} = join\\(([^;]*?)\\);`, 's'));
      expect(parent).not.toBeNull();
      parts.unshift(...[...parent![1].matchAll(/'([^']+)'/g)].map((m) => m[1]));
      head = parent![1].trim().split(',')[0].trim();
    }
    resolved.push(parts.join('/'));
  }
  return resolved.sort();
}

describe('codegen drift guard has no dead clause', () => {
  it('guards exactly the files codegen-python.ts writes', () => {
    expect(guardPaths().sort()).toEqual(generatedPaths());
  });

  it('every guarded path exists, so no clause is a permanent no-op', () => {
    for (const p of guardPaths()) {
      expect({ path: p, exists: existsSync(join(ROOT, p)) }).toEqual({
        path: p,
        exists: true,
      });
    }
  });

  it('nothing in the repo writes under schema/, so schema/ is not on the guard', () => {
    // If a real schema generator is ever added, this fails and whoever adds it
    // must add schema/ to the guard — that is the point of asserting it.
    // Searched in the places a generator could live. `tests/` is excluded on
    // purpose: this very file quotes the pattern, and a test writing under
    // schema/ would not be something the CI guard needs to cover anyway.
    const res = spawnSync(
      'grep',
      [
        '-rlE',
        String.raw`(writeFileSync|writeFile|write_text|createWriteStream)\([^)]*schema/`,
        'scripts',
        'src',
        'packages',
        'python/src',
      ],
      { cwd: ROOT, encoding: 'utf-8' },
    );
    // grep exits 1 with no output when there is no match — that is the pass.
    expect({ status: res.status, stdout: res.stdout.trim() }).toEqual({
      status: 1,
      stdout: '',
    });
  }, 20000);
});

describe('hand-maintained _generated files do not claim to be generated', () => {
  const handMaintained = [
    'python/src/tzun_sdk/_generated/canonical.py',
    'python/src/tzun_sdk/_generated/chain.py',
  ];

  it.each(handMaintained)('%s is labelled hand-maintained', (rel) => {
    const head = read(rel).split('\n').slice(0, 15).join('\n');
    expect(head).toMatch(/HAND-MAINTAINED/);
    // The banner must not name a source path that does not exist.
    expect(existsSync(join(ROOT, 'src', 'engine', 'canonical.ts'))).toBe(false);
    expect(head).not.toMatch(/^# AUTOGENERATED/m);
    expect(head).not.toMatch(/src\/engine\/canonical\.ts/);
  });

  it('codegen-python.ts really does leave those files alone', () => {
    const src = read('scripts/codegen-python.ts');
    expect(src).not.toMatch(/writeFileSync\([^)]*canonical\.py/);
    expect(src).not.toMatch(/writeFileSync\([^)]*chain\.py/);
  });
});

describe('the documented way to extend the conformance corpus runs', () => {
  it('the canonical-vector generator prints the corpus, V17..V21 and V26..V27 among it', () => {
    // A generator that imports a deleted path dies with MODULE_NOT_FOUND, and
    // tsconfig.json excludes scripts/, so `tsc --noEmit` never sees it. The
    // generator prints its file and writes nothing; the driver
    // (scripts/regenerate-vectors.ts) writes it, and its --check run is
    // tests/cross-sdk/ts/vector-files-current.test.ts.
    const out = execFileSync(
      'pnpm',
      ['exec', 'tsx', 'scripts/generate-v1.0-canonical-vectors.ts'],
      { cwd: ROOT, encoding: 'utf-8', stdio: ['ignore', 'pipe', 'pipe'], maxBuffer: 64 * 1024 * 1024 },
    );
    const file = JSON.parse(out) as { vectors: Array<{ id: string }> };
    const ids = file.vectors.map((c) => c.id);
    expect(ids).toEqual(expect.arrayContaining(['V17', 'V18', 'V19', 'V20', 'V21', 'V26', 'V27']));
    expect(out).toBe(read('vectors/v1.0-canonical-vectors.json'));
  }, 60000);

  it('is reachable through a package script that uses a real devDependency', () => {
    const pkg = JSON.parse(read('package.json')) as { scripts: Record<string, string>; devDependencies: Record<string, string> };
    const script = pkg.scripts['regenerate:vectors'];
    expect(script).toBeDefined();
    // `ts-node` is not a devDependency here, so a script that shells to
    // `npx ts-node` would download an arbitrary latest ts-node at run time.
    expect(script).not.toMatch(/ts-node/);
    const runner = script.match(/(tsx|ts-node|esbuild-register)/)?.[1];
    expect(runner).toBeDefined();
    expect(pkg.devDependencies[runner!]).toBeDefined();
  });
});
